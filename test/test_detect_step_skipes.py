    return_y_data = data['smoothed_data']
    diff_before = max(np.diff(skipe_y))
    diff_after = max(np.diff(return_y_data))
    assert diff_after < diff_before
    # 判断标准2 标准差降低
    assert np.std(return_y_data) < np.std(skipe_y)


