async def test_detect_step_skipes(async_client):
    x_data = []
    step_y = []
    skipe_y = []
    for d in test_data: 
        x_data.append(d['x'])
        step_y.append(float(d['step_y']))
        skipe_y.append(float(d['skipe_y']))
    print(x_data)
    print(step_y)
    """
    测试台阶
    目标： 去除台阶
    """
    step_json = {'x_data': x_data, 'y_data': step_y, 'k': 10}
    step_response = await async_client.post(TEST_URL, json=step_json)
    data = step_response.json()
    assert data['code'] == 0
    return_y_data = data['smoothed_data']
    jump_count_before = np.sum(np.abs(np.diff(step_y)) > 0.01)
    jump_count_after = np.sum(np.abs(np.diff(return_y_data)) > 0.01)
    assert jump_count_after < jump_count_before
    
    """
    测试倒刺
    目标： 去除倒刺
    """
    spike_json = {'x_data': x_data, 'y_data': skipe_y, 'k': 10}
    spike_response = await async_client.post(TEST_URL, json=spike_json)
    data = spike_response.json()
